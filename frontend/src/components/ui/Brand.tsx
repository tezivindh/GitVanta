import React from 'react';
import { Link } from 'react-router-dom';
import clsx from 'clsx';
import { Moon, Sun, Sparkles, KeyRound } from 'lucide-react';
import { useThemeStore } from '../../store/themeStore';
import { AIMeta } from '../../types';

/** Three columns of contribution cells, stepping up to the right: a score rising. */
const MARK_CELLS: Array<[number, number, number]> = [
  // [column, row, level]
  [0, 0, 0], [1, 0, 0], [2, 0, 4],
  [0, 1, 0], [1, 1, 3], [2, 1, 4],
  [0, 2, 2], [1, 2, 3], [2, 2, 4],
];

/** The GitVanta mark. Uses the heat ramp, so it follows the theme. */
export const LogoMark: React.FC<{ className?: string }> = ({ className }) => (
  <svg viewBox="0 0 32 32" className={clsx('h-7 w-7', className)} aria-hidden="true">
    {MARK_CELLS.map(([c, r, l]) => (
      <rect
        key={`${c}${r}`}
        x={1 + c * 10.5}
        y={1 + r * 10.5}
        width="9"
        height="9"
        rx="2"
        style={{ fill: `var(--heat-${l})` }}
      />
    ))}
  </svg>
);

export const Logo: React.FC<{ to?: string; className?: string }> = ({ to = '/', className }) => (
  <Link to={to} className={clsx('flex items-center gap-2.5 rounded-md', className)} aria-label="GitVanta home">
    <LogoMark />
    <span className="font-display text-[1.15rem] text-gray-900 dark:text-white">GitVanta</span>
  </Link>
);

export const ThemeToggle: React.FC<{ className?: string }> = ({ className }) => {
  const { isDark, toggle } = useThemeStore();
  return (
    <button
      type="button"
      onClick={toggle}
      className={clsx(
        'rounded-lg p-2 text-gray-600 transition-colors hover:bg-gray-100 hover:text-gray-900 dark:text-gray-400 dark:hover:bg-gray-800 dark:hover:text-white',
        className
      )}
      aria-label={isDark ? 'Switch to light theme' : 'Switch to dark theme'}
      title={isDark ? 'Light theme' : 'Dark theme'}
    >
      {isDark ? <Sun className="h-5 w-5" /> : <Moon className="h-5 w-5" />}
    </button>
  );
};

/** "Written by Groq (openai/gpt-oss-120b) with your key" under every AI result. */
export const AIAttribution: React.FC<{ ai: AIMeta | null | undefined; className?: string }> = ({ ai, className }) => {
  if (!ai) return null;
  const Icon = ai.source === 'user' ? KeyRound : Sparkles;
  return (
    <p className={clsx('flex items-center gap-1.5 text-xs text-gray-500 dark:text-gray-400', className)}>
      <Icon className="h-3.5 w-3.5" aria-hidden="true" />
      <span>
        Generated by {ai.providerLabel} <span className="font-mono">({ai.model})</span>
        {ai.source === 'user' ? ' using your API key' : ' using the GitVanta key'}
      </span>
    </p>
  );
};
